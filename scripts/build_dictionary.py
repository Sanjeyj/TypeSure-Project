def nfc(w: str) -> str:
    return unicodedata.normalize("NFC", w.strip())

def is_valid_tamil_word(w: str) -> bool:
    if not w or len(w) < 1:
        return False
    # Must contain at least one Tamil character
    has_tamil = any('\u0B80' <= ch <= '\u0BFF' for ch in w)
    # Must not contain Latin letters or digits
    has_disallowed = any(ch.isascii() and (ch.isalpha() or ch.isdigit()) for ch in w)
    return has_tamil and not has_disallowed

